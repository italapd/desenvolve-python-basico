# Aula 2.2 - Tipos de Dados
# Exercícios

# 1. Crie variáveis para armazenar um número inteiro, um número decimal, uma string e um valor booleano.

# 2. Mostre na tela o tipo de cada variável criada usando a função type().

# 3. Converta o número inteiro para float e mostre o resultado.

# 4. Converta o número decimal para inteiro e mostre o resultado.

# 5. Converta a string para inteiro (tente com uma string numérica, ex: '123') e mostre o resultado.

# 6. Converta o valor booleano para inteiro e mostre o resultado.

# 7. Peça para o usuário digitar um número e mostre se ele é par ou ímpar.

# 8. Peça para o usuário digitar sua idade e mostre uma mensagem dizendo se ele é maior de idade (18 anos ou mais).

# 9. Crie uma variável que armazene o resultado da soma de um inteiro e um float. Mostre o valor e o tipo da variável.

# 10. Desafio: Peça para o usuário digitar um valor e mostre se ele é um número inteiro, float, string ou booleano (dica: use try/except para testar as conversões).
